function sanitize(obj) {
  return JSON.parse(JSON.stringify(obj, (k, v) => (v === undefined ? null : v)));
}

async function run() {
  console.log("===============================================================================");
  console.log("🏭 UMESH FENCING WORKS — CLOUD FIRESTORE SEEDING & REPLICATION");
  console.log("===============================================================================");
  console.log(`Target Project: ${firebaseConfig.projectId}`);
  console.log(`Admin Whitelist: umeshfencingworks@gmail.com`);
  console.log(`Checking connection to Google Cloud Firestore...`);

  // Step 1: Initialize Firebase App & Firestore targeting database 'default' (or '(default)')
  const app = initializeApp(firebaseConfig);
  let db;
  let activeDatabaseId = "default";
  try {
    db = getFirestore(app, "default");
  } catch (err) {
    db = getFirestore(app);
    activeDatabaseId = "(default)";
  }

  console.log(`\n📡 Connected to Firestore (Database: '${activeDatabaseId}')! Starting data push...`);

  let customerCount = 0;
  let docCount = 0;
  let paymentCount = 0;
  let logCount = 0;

  // 1. Seed Customers
  console.log(`\n[1/4] Pushing ${CUSTOMERS.length} Customers...`);
  for (const c of CUSTOMERS) {
    const ref = doc(db, "customers", c.id);
    await setDoc(ref, sanitize({ ...c, _syncedAt: new Date().toISOString() }), { merge: true });
    customerCount++;
    console.log(`  ✓ [Customer] ${c.id}: ${c.company || c.name} (${c.phone})`);
  }

  // 2. Seed Invoices & Bills
  console.log(`\n[2/4] Pushing ${DOCUMENTS.length} Invoices & Retail Bills...`);
  for (const d of DOCUMENTS) {
    const ref = doc(db, "documents", d.id);
    await setDoc(ref, sanitize({ ...d, _syncedAt: new Date().toISOString() }), { merge: true });
    docCount++;
    console.log(`  ✓ [${d.documentType.toUpperCase()}] ${d.documentNumber}: ₹${d.grandTotal.toLocaleString("en-IN")} — ${d.customerSnapshot?.company || d.customerSnapshot?.name}`);
  }

  // 3. Seed Payments
  console.log(`\n[3/4] Pushing ${PAYMENTS.length} Payment Receipts...`);
  for (const p of PAYMENTS) {
    const ref = doc(db, "payments", p.id);
    await setDoc(ref, sanitize({ ...p, _syncedAt: new Date().toISOString() }), { merge: true });
    paymentCount++;
    console.log(`  ✓ [Payment] ${p.id}: ₹${p.amount.toLocaleString("en-IN")} for ${p.documentNumber} (${p.paymentMethod})`);
  }

  // 4. Seed Audit Logs
  console.log(`\n[4/4] Pushing ${AUDIT_LOGS.length} Audit Logs...`);
  for (const a of AUDIT_LOGS) {
    const ref = doc(db, "auditLogs", a.id);
    await setDoc(ref, sanitize({ ...a, _syncedAt: new Date().toISOString() }), { merge: true });
    logCount++;
    console.log(`  ✓ [Audit Log] ${a.action}: ${a.details}`);
  }

  console.log("\n===============================================================================");
  console.log("🎉 SUCCESS: ALL RECORDS SUCCESSFULLY PUSHED TO CLOUD FIRESTORE!");
  console.log("===============================================================================");
  console.log(`Collections Populated:`);
  console.log(`  • customers:   ${customerCount} records`);
  console.log(`  • documents:   ${docCount} records (Tax Invoices & Retail Bills)`);
  console.log(`  • payments:    ${paymentCount} records`);
  console.log(`  • audit_logs:  ${logCount} records`);
  console.log(`\nOpen Firebase Console to view your live data:`);
  console.log(`https://console.firebase.google.com/project/${firebaseConfig.projectId}/firestore/databases/-default-/data`);
  console.log("===============================================================================\n");
  process.exit(0);
}

run().catch((err) => {
  console.error("\n❌ Push failed with error:", err.message);
  process.exit(1);
});
